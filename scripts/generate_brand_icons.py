#!/usr/bin/env python3
"""Generate Android brand resources from the checked-in upstream SVGs.

Requires rsvg-convert (librsvg) and Pillow. Run from any directory.
"""
from copy import deepcopy
from io import BytesIO
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
SVG = "{http://www.w3.org/2000/svg}"
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("android", ANDROID)
SCALE, INSET = 0.66, 21


def attrs(**values):
    return {f"{{{ANDROID}}}{key}": str(value) for key, value in values.items()}


def write_xml(path, element):
    ET.indent(element, space="    ")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                    '<!-- Generated by scripts/generate_brand_icons.py. -->\n'
                    + ET.tostring(element, encoding="unicode") + "\n")


def convert(element):
    tag = element.tag.removeprefix(SVG)
    if tag == "g":
        tx, ty, scale = map(float, re.fullmatch(
            r"translate\(([-.\d]+) ([-.\d]+)\) scale\(([-.\d]+)\)",
            element.attrib["transform"]).groups())
        group = ET.Element("group", attrs(translateX=tx, translateY=ty,
                                         scaleX=scale, scaleY=scale))
        group.extend(convert(child) for child in element)
        return group
    if tag == "circle":
        x, y, r = (float(element.attrib[key]) for key in ("cx", "cy", "r"))
        data = f"M{x-r},{y}a{r},{r} 0 1,0 {2*r},0a{r},{r} 0 1,0 {-2*r},0Z"
    else:
        assert tag == "path", tag
        data = element.attrib["d"]
    values = {"pathData": data, "fillColor": element.get("fill", "#000000")}
    if values["fillColor"] == "none":
        values["fillColor"] = "#00000000"
    for source, dest in (("stroke", "strokeColor"), ("stroke-width", "strokeWidth"),
                         ("stroke-linecap", "strokeLineCap"),
                         ("stroke-linejoin", "strokeLineJoin")):
        if source in element.attrib:
            values[dest] = element.attrib[source]
    return ET.Element("path", attrs(**values))


def vector(art, *, preview=False, background=None):
    # A 72dp launcher viewport crops 18dp from each edge of the 108dp layers.
    size = 72 if preview else 108
    vector = ET.Element("vector", attrs(width=f"{size}dp", height=f"{size}dp",
                                       viewportWidth=size, viewportHeight=size))
    if background:
        ET.SubElement(vector, "path", attrs(fillColor=background,
            pathData=f"M0,0H{size}V{size}H0Z"))
    offset = INSET - (18 if preview else 0)
    outer = ET.SubElement(vector, "group", attrs(
        scaleX=SCALE, scaleY=SCALE, translateX=offset, translateY=offset))
    outer.append(convert(art))
    return vector


def render(art, *, background=None, adaptive=False, size=432):
    viewport = "0 0 108 108" if adaptive else "18 18 72 72"
    root = ET.Element("svg", xmlns=SVG[1:-1], viewBox=viewport)
    if background:
        ET.SubElement(root, "rect", width="108", height="108", fill=background)
    group = ET.SubElement(root, "g", transform=f"translate({INSET} {INSET}) scale({SCALE})")
    group.append(deepcopy(art))
    png = subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size)],
        input=ET.tostring(root), stdout=subprocess.PIPE, check=True).stdout
    return Image.open(BytesIO(png)).convert("RGBA")


def monochrome(art, *, adaptive=True, size=432):
    # The two-color artwork becomes a true alpha mask: cream details are holes,
    # navy details are opaque. Preserve antialiasing, eyes, glasses and pupils.
    image = render(art, adaptive=adaptive, size=size)
    pixels = image.load()
    alpha = []
    for y in range(image.height):
        for x in range(image.width):
            r, _, _, a = pixels[x, y]
            alpha.append((255, 255, 255, round(a * max(0, min(1, (242-r)/214)))))
    image.putdata(alpha)
    return image


def generate():
    for name in ("hootbook", "hoot", "book"):
        source = ET.parse(ROOT / f"branding/{name}-icon-white.svg").getroot()
        art = source.find(f"{SVG}g")
        write_xml(RES / f"drawable/ic_{name}_foreground.xml", vector(art))
        mono_dir = RES / "drawable-nodpi"
        mono_dir.mkdir(exist_ok=True)
        monochrome(art).save(mono_dir / f"ic_{name}_monochrome.png")
        for shade, color in (("white", "#FFFFFF"), ("cream", "#F2EDE3")):
            variant = ET.parse(ROOT / f"branding/{name}-icon-{shade}.svg").getroot()
            assert variant.find(f"{SVG}rect").get("fill") == color
            assert ET.tostring(variant.find(f"{SVG}g")) == ET.tostring(art)
            write_xml(RES / f"drawable/{name}_icon_{shade}.xml",
                      vector(art, preview=True, background=color))
            icon = ET.Element("adaptive-icon")
            ET.SubElement(icon, "background", attrs(drawable=f"@color/brand_{shade}"))
            ET.SubElement(icon, "foreground", attrs(drawable=f"@drawable/ic_{name}_foreground"))
            ET.SubElement(icon, "monochrome", attrs(drawable=f"@drawable/ic_{name}_monochrome"))
            for suffix in ("", "_round"):
                write_xml(RES / f"mipmap-anydpi-v26/ic_launcher_{name}_{shade}{suffix}.xml", icon)
            if name == "hootbook" and shade == "white":
                for suffix in ("", "_round"):
                    write_xml(RES / f"mipmap-anydpi-v26/ic_launcher{suffix}.xml", icon)
        if name == "hootbook":
            # Notification small icons use alpha, never the opaque app-icon tile.
            monochrome(art, adaptive=False, size=96).save(mono_dir / "ic_notification_hootbook.png")
            for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96),
                                  ("xxhdpi", 144), ("xxxhdpi", 192)):
                folder = RES / f"mipmap-{density}"
                square = render(art, background="#FFFFFF", size=size)
                square.save(folder / "ic_launcher.webp", lossless=True)
                # Circle mask at high resolution for smooth edges.
                mask = Image.new("L", (size*4, size*4))
                ImageDraw.Draw(mask).ellipse((0, 0, size*4, size*4), fill=255)
                square.putalpha(mask.resize((size, size), Image.Resampling.LANCZOS))
                square.save(folder / "ic_launcher_round.webp", lossless=True)
                render(art, adaptive=True, size=round(size*108/48)).save(
                    folder / "ic_launcher_foreground.webp", lossless=True)
            # Store art has no baked-in corners; the store applies its own mask.
            store = deepcopy(source)
            store.find(f"{SVG}rect").attrib.pop("rx")
            for target in (ROOT / "app/src/main/ic_launcher-playstore.png",
                           ROOT / "fastlane/metadata/android/en-US/images/icon.png"):
                png = subprocess.run(["rsvg-convert", "-w", "512", "-h", "512"],
                    input=ET.tostring(store), stdout=subprocess.PIPE, check=True).stdout
                target.write_bytes(png)


if __name__ == "__main__":
    generate()
